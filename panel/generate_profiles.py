def pick_age(rng: random.Random) -> int:
    lo, hi = rng.choice(AGE_BRACKETS)
    return rng.randint(lo, hi)


def build_profile(idx: int, sector: str, rng: random.Random) -> dict:
    gender = rng.choice(["זכר", "נקבה"])
    names = MALE_NAMES if gender == "זכר" else FEMALE_NAMES
    first = rng.choice(names[sector])
    last = rng.choice(LAST_NAMES[sector])
    age = pick_age(rng)
    region = rng.choice(REGIONS[sector])
    political = rng.choice(POLITICAL_BY_SECTOR[sector])
    profession = rng.choice(PROFESSIONS)
    family = rng.choice(FAMILY_STATUSES)
    background = rng.choice(VALUES_SNIPPETS[sector])

    return {
        "id": f"p{idx:04d}",
        "name": f"{first} {last}",
        "gender": gender,
        "age": age,
        "sector": sector,
        "region": region,
        "political_leaning": political,
        "profession": profession,
        "family_status": family,
        "background": background,
    }


def generate(n: int, seed: int = SEED) -> list[dict]:
    rng = random.Random(seed)
    sectors, weights = zip(*SECTOR_WEIGHTS)
    profiles = []
    seen = set()
    idx = 1
    attempts = 0
    while len(profiles) < n and attempts < n * 20:
        attempts += 1
        sector = rng.choices(sectors, weights=weights, k=1)[0]
        profile = build_profile(idx, sector, rng)
        key = (profile["name"], profile["age"], profile["region"])
        if key in seen:
            continue
        seen.add(key)
        profiles.append(profile)
        idx += 1
    return profiles


def main():
    parser = argparse.ArgumentParser(description="יצירת מאגר פרופילים ישראליים מגוונים")
    parser.add_argument("--n", type=int, default=220, help="מספר פרופילים ליצירה")
    parser.add_argument("--out", default="panel/profiles.json", help="קובץ פלט")
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    profiles = generate(args.n, args.seed)
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(profiles, f, ensure_ascii=False, indent=2)

    print(f"נוצרו {len(profiles)} פרופילים ונשמרו ל-{args.out}")
    from collections import Counter
    counts = Counter(p["sector"] for p in profiles)
    for sector, count in counts.most_common():
        print(f"  {sector}: {count}")


if __name__ == "__main__":
    main()
